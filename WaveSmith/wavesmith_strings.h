/*
 * wavesmith_strings.h -- WaveSmith's words, in English: the SEED of its
 * catalog. Not included by the program; tools/gen_catalog.py reads it and
 * writes catalogs/WaveSmith.cd, WaveSmith_cat.h, wavesmith_msg.h and
 * wavesmith_catver.h (each name becomes a GetString() lookup):
 *
 *   python3 tools/gen_catalog.py --name WaveSmith --prefix WS \
 *           --srcdir WaveSmith gen
 *
 * The ids are numbered in this file's order: a change here means running
 * that again, which restamps the translations' version; a translation that
 * lags behind falls back to English instead of showing the wrong words.
 *
 * Every table these fill -- the menus, the bubbles, the handles' labels --
 * is filled at run time: a lookup is a function call and cannot sit in a
 * static initializer (the menu table holds the ids till then).
 *
 * WIDTH: the window fits 640 x 256 at Topaz 8 in English. A translated
 * button or field label must be no longer than the longest English one in
 * its row, or the window outgrows a PAL screen.
 *
 * Formats: %ld for a number, %s for a text (Text_Fmt(), RawDoFmt's way).
 */

